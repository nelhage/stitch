//! `stitch ssh` argument construction, and `stitch ssh-config` generation and
//! installation.
//!
//! Both put the absolute path of the running `stitch` binary into an `ssh`
//! `ProxyCommand`. `ssh` performs `%`-token expansion on that string and then
//! runs it with the user's shell (`$SHELL -c "exec <command>"`), so the path is
//! shell-quoted and then has any `%` doubled.

use std::ffi::{OsStr, OsString};
use std::fs::{self, DirBuilder, OpenOptions};
use std::io::{self, Write};
use std::os::unix::fs::{DirBuilderExt, OpenOptionsExt, PermissionsExt};
use std::os::unix::process::CommandExt;
use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::{Context, bail};

/// The suffix which `stitch ssh-config` routes through `stitch`.
pub const HOST_SUFFIX: &str = ".stitch";

/// Name of the generated file, in `~/.ssh`.
pub const CONF_FILE_NAME: &str = "stitch.conf";

/// The line `stitch ssh-config` ensures is at the top of `~/.ssh/config`.
pub const INCLUDE_LINE: &str = "Include stitch.conf";

/// Options which make an `ssh` running over a stitch tunnel tolerate stalls:
/// it never sees network failures, only pauses, which must not kill it.
const STALL_TOLERANT_OPTIONS: [(&str, &str); 2] =
    [("ServerAliveInterval", "0"), ("TCPKeepAlive", "no")];

/// Quote `s` for a POSIX shell, leaving it bare if it is obviously safe.
pub fn shell_quote(s: &str) -> String {
    let safe = |c: char| c.is_ascii_alphanumeric() || "_@%+=:,./-".contains(c);
    if !s.is_empty() && s.chars().all(safe) {
        s.to_owned()
    } else {
        format!("'{}'", s.replace('\'', r"'\''"))
    }
}

/// The `ProxyCommand` value which runs `exe` followed by `args`. `args` is
/// inserted verbatim (it may contain `ssh` `%` tokens such as `%h`); `exe` is
/// shell-quoted and `%`-escaped.
pub fn proxy_command(exe: &Path, args: &str) -> anyhow::Result<String> {
    let exe = exe
        .to_str()
        .with_context(|| format!("path to stitch is not valid UTF-8: {}", exe.display()))?;
    if exe.contains(['\n', '\r']) {
        bail!("path to stitch contains a newline: {exe:?}");
    }
    Ok(format!("{} {args}", shell_quote(exe).replace('%', "%%")))
}

/// The arguments (excluding `argv[0]`) with which `stitch ssh HOST args...`
/// runs `ssh`:
/// `-o ProxyCommand=<exe> tunnel %h -o ServerAliveInterval=0 -o TCPKeepAlive=no HOST args...`
pub fn ssh_args(exe: &Path, host: &OsStr, args: &[OsString]) -> anyhow::Result<Vec<OsString>> {
    let mut out: Vec<OsString> = vec![
        "-o".into(),
        format!("ProxyCommand={}", proxy_command(exe, "tunnel %h")?).into(),
    ];
    for (k, v) in STALL_TOLERANT_OPTIONS {
        out.push("-o".into());
        out.push(format!("{k}={v}").into());
    }
    out.push(host.to_owned());
    out.extend(args.iter().cloned());
    Ok(out)
}

/// `stitch ssh`: replace this process with `ssh` (see [`ssh_args`]). Only
/// returns on failure.
pub fn exec_ssh(host: &OsStr, args: &[OsString]) -> anyhow::Error {
    let exe = match std::env::current_exe().context("cannot find path to stitch") {
        Ok(exe) => exe,
        Err(e) => return e,
    };
    let args = match ssh_args(&exe, host, args) {
        Ok(a) => a,
        Err(e) => return e,
    };
    log::debug!("exec ssh {args:?}");
    let err = Command::new("ssh").args(args).exec();
    anyhow::Error::new(err).context("cannot run ssh")
}

/// The contents of `~/.ssh/stitch.conf`, which routes `ssh HOST.stitch`
/// through `stitch tunnel`.
pub fn config_snippet(exe: &Path) -> anyhow::Result<String> {
    let mut s = String::new();
    s.push_str("# Generated by `stitch ssh-config`; re-running it will overwrite this file.\n");
    s.push_str(&format!("Host *{HOST_SUFFIX}\n"));
    s.push_str(&format!(
        "    ProxyCommand {}\n",
        proxy_command(exe, &format!("tunnel --strip-suffix {HOST_SUFFIX} %h"))?
    ));
    for (k, v) in STALL_TOLERANT_OPTIONS {
        s.push_str(&format!("    {k} {v}\n"));
    }
    Ok(s)
}

/// What [`install`] did to `~/.ssh/config`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum IncludeStatus {
    /// The `Include` line was added at the top.
    Added,
    /// An `Include` of `stitch.conf` was already present before any `Host` or
    /// `Match` block; nothing was changed.
    AlreadyPresent,
    /// An `Include` of `stitch.conf` is present, but only inside a `Host` or
    /// `Match` block, where it may not apply to `*.stitch` hosts. Nothing was
    /// changed, to avoid duplicating it; the user should check their config.
    PresentInBlock,
}

/// The result of [`install`].
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct InstallOutcome {
    /// `~/.ssh/stitch.conf`.
    pub conf_path: PathBuf,
    /// Whether `stitch.conf` was (re)written, i.e. its contents changed.
    pub conf_written: bool,
    /// `~/.ssh/config`.
    pub config_path: PathBuf,
    pub include: IncludeStatus,
}

/// The user's home directory: `$HOME`, falling back to the password database.
pub fn home_dir() -> anyhow::Result<PathBuf> {
    if let Some(h) = std::env::var_os("HOME").filter(|h| !h.is_empty()) {
        return Ok(h.into());
    }
    let uid = nix::unistd::getuid();
    match nix::unistd::User::from_uid(uid) {
        Ok(Some(u)) => Ok(u.dir),
        _ => bail!("cannot determine home directory: HOME is not set"),
    }
}

/// `stitch ssh-config`: write `snippet` to `<home>/.ssh/stitch.conf`, and
/// ensure that `<home>/.ssh/config` includes it before any `Host` or `Match`
/// block. Creates `<home>/.ssh` (mode 0700) and the files (mode 0600) if
/// necessary. Idempotent: never adds a second `Include`, and preserves
/// existing content, modes, and symlinks.
pub fn install(home: &Path, snippet: &str) -> anyhow::Result<InstallOutcome> {
    let ssh_dir = home.join(".ssh");
    match DirBuilder::new().mode(0o700).create(&ssh_dir) {
        Ok(()) => {}
        Err(e) if e.kind() == io::ErrorKind::AlreadyExists => {}
        Err(e) => return Err(e).with_context(|| format!("cannot create {}", ssh_dir.display())),
    }

    let conf_path = ssh_dir.join(CONF_FILE_NAME);
    let conf_written = match fs::read(&conf_path) {
        Ok(existing) if existing == snippet.as_bytes() => false,
        _ => {
            write_atomically(&conf_path, snippet.as_bytes())?;
            true
        }
    };

    let config_path = ssh_dir.join("config");
    let existing = match fs::read(&config_path) {
        Ok(b) => Some(
            String::from_utf8(b)
                .with_context(|| format!("{} is not valid UTF-8", config_path.display()))?,
        ),
        Err(e) if e.kind() == io::ErrorKind::NotFound => None,
        Err(e) => {
            return Err(e).with_context(|| format!("cannot read {}", config_path.display()));
        }
    };
    let include = match existing.as_deref().map(|c| find_include(c, home)) {
        Some(Some(true)) => IncludeStatus::AlreadyPresent,
        Some(Some(false)) => IncludeStatus::PresentInBlock,
        Some(None) | None => {
            let mut new = format!("{INCLUDE_LINE}\n");
            if let Some(c) = &existing {
                new.push_str(c);
            }
            write_atomically(&config_path, new.as_bytes())?;
            IncludeStatus::Added
        }
    };

    Ok(InstallOutcome {
        conf_path,
        conf_written,
        config_path,
        include,
    })
}

/// Split an `ssh_config` line into keyword and arguments, handling the
/// optional `=` and double-quoted arguments. Returns `None` for blank lines
/// and comments.
fn config_words(line: &str) -> Option<(String, Vec<String>)> {
    let line = line.trim();
    if line.is_empty() || line.starts_with('#') {
        return None;
    }
    let end = line
        .find(|c: char| c.is_whitespace() || c == '=')
        .unwrap_or(line.len());
    let keyword = line[..end].to_ascii_lowercase();
    let rest = line[end..].trim_start();
    let rest = rest.strip_prefix('=').unwrap_or(rest);
    let mut args = Vec::new();
    let mut cur = String::new();
    let mut in_quotes = false;
    let mut have = false;
    for c in rest.chars() {
        match c {
            '"' => {
                in_quotes = !in_quotes;
                have = true;
            }
            c if c.is_whitespace() && !in_quotes => {
                if have {
                    args.push(std::mem::take(&mut cur));
                    have = false;
                }
            }
            c => {
                cur.push(c);
                have = true;
            }
        }
    }
    if have {
        args.push(cur);
    }
    Some((keyword, args))
}

/// Look for an `Include` of `stitch.conf` in an `ssh_config`. Returns
/// `Some(true)` if one appears before the first `Host`/`Match` line,
/// `Some(false)` if one appears only after, and `None` if there is none.
fn find_include(config: &str, home: &Path) -> Option<bool> {
    let absolute = home.join(".ssh").join(CONF_FILE_NAME);
    let names = [
        CONF_FILE_NAME.to_owned(),
        format!("~/.ssh/{CONF_FILE_NAME}"),
        absolute.to_string_lossy().into_owned(),
    ];
    let mut global = true;
    let mut found_in_block = false;
    for line in config.lines() {
        let Some((keyword, args)) = config_words(line) else {
            continue;
        };
        match keyword.as_str() {
            "host" | "match" => global = false,
            "include" if args.iter().any(|a| names.contains(a)) => {
                if global {
                    return Some(true);
                }
                found_in_block = true;
            }
            _ => {}
        }
    }
    found_in_block.then_some(false)
}

/// Replace the contents of `path` atomically (via a temporary file and
/// `rename`). If `path` is a symlink, its target is replaced, leaving the
/// symlink in place. An existing file's mode is preserved; a new file gets
/// mode 0600.
fn write_atomically(path: &Path, contents: &[u8]) -> anyhow::Result<()> {
    let (target, mode) = match fs::canonicalize(path) {
        Ok(real) => {
            let mode = fs::metadata(&real)
                .with_context(|| format!("cannot stat {}", real.display()))?
                .permissions()
                .mode()
                & 0o7777;
            (real, mode)
        }
        Err(e) if e.kind() == io::ErrorKind::NotFound && fs::symlink_metadata(path).is_err() => {
            (path.to_owned(), 0o600)
        }
        Err(e) => return Err(e).with_context(|| format!("cannot resolve {}", path.display())),
    };
    let dir = target.parent().context("path has no parent directory")?;
    let name = target
        .file_name()
        .context("path has no file name")?
        .to_string_lossy();
    let tmp = dir.join(format!(".{name}.stitch-tmp-{}", std::process::id()));
    let result = (|| -> io::Result<()> {
        let mut f = OpenOptions::new()
            .write(true)
            .create_new(true)
            .mode(mode)
            .open(&tmp)?;
        // `mode` is subject to the umask; set it exactly.
        f.set_permissions(fs::Permissions::from_mode(mode))?;
        f.write_all(contents)?;
        f.sync_all()?;
        fs::rename(&tmp, &target)
    })();
    if result.is_err() {
        let _ = fs::remove_file(&tmp);
    }
    result.with_context(|| format!("cannot write {}", target.display()))
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::os::unix::fs::{MetadataExt, symlink};

    #[test]
    fn quoting() {
        assert_eq!(shell_quote("/usr/bin/stitch"), "/usr/bin/stitch");
        assert_eq!(shell_quote(""), "''");
        assert_eq!(shell_quote("a b"), "'a b'");
        assert_eq!(shell_quote("it's"), r"'it'\''s'");
        assert_eq!(shell_quote("$HOME"), "'$HOME'");
    }

    /// Mimic `ssh`'s handling of a `ProxyCommand`: expand `%%` and `%h`, run
    /// it with `sh -c`, and return the resulting argv.
    fn run_like_ssh(proxy_command: &str, host: &str) -> Vec<String> {
        let mut expanded = String::new();
        let mut chars = proxy_command.chars();
        while let Some(c) = chars.next() {
            if c == '%' {
                match chars.next() {
                    Some('%') => expanded.push('%'),
                    Some('h') => expanded.push_str(host),
                    other => panic!("unexpected token %{other:?}"),
                }
            } else {
                expanded.push(c);
            }
        }
        let out = Command::new("sh")
            .arg("-c")
            .arg(format!(r#"set -- {expanded}; printf '%s\0' "$@""#))
            .output()
            .unwrap();
        assert!(out.status.success());
        String::from_utf8(out.stdout)
            .unwrap()
            .split_terminator('\0')
            .map(str::to_owned)
            .collect()
    }

    #[test]
    fn proxy_command_survives_ssh_and_shell() {
        for exe in [
            "/usr/bin/stitch",
            "/home/me/my tools/stitch",
            "/opt/100%/it's \"$HOME\" `x`/stitch",
        ] {
            let pc = proxy_command(Path::new(exe), "tunnel %h").unwrap();
            assert_eq!(
                run_like_ssh(&pc, "example.com"),
                [exe, "tunnel", "example.com"],
                "{pc}"
            );
        }
        assert!(proxy_command(Path::new("/a\nb"), "x").is_err());
    }

    #[test]
    fn ssh_argument_construction() {
        let args = ssh_args(
            Path::new("/bin/stitch"),
            OsStr::new("host"),
            &["-v".into(), "ls".into(), "-l".into()],
        )
        .unwrap();
        assert_eq!(
            args,
            [
                "-o",
                "ProxyCommand=/bin/stitch tunnel %h",
                "-o",
                "ServerAliveInterval=0",
                "-o",
                "TCPKeepAlive=no",
                "host",
                "-v",
                "ls",
                "-l"
            ]
        );
    }

    #[test]
    fn snippet() {
        let s = config_snippet(Path::new("/opt/50%/stitch")).unwrap();
        assert!(s.contains("\nHost *.stitch\n"), "{s}");
        assert!(
            s.contains("\n    ProxyCommand /opt/50%%/stitch tunnel --strip-suffix .stitch %h\n"),
            "{s}"
        );
        assert!(s.contains("\n    ServerAliveInterval 0\n"));
        assert!(s.contains("\n    TCPKeepAlive no\n"));
    }

    fn mode(p: &Path) -> u32 {
        fs::metadata(p).unwrap().mode() & 0o7777
    }

    #[test]
    fn install_fresh() {
        let home = tempfile::tempdir().unwrap();
        let out = install(home.path(), "SNIPPET\n").unwrap();
        let ssh = home.path().join(".ssh");
        assert_eq!(mode(&ssh), 0o700);
        assert_eq!(out.conf_path, ssh.join("stitch.conf"));
        assert_eq!(out.config_path, ssh.join("config"));
        assert!(out.conf_written);
        assert_eq!(out.include, IncludeStatus::Added);
        assert_eq!(fs::read_to_string(&out.conf_path).unwrap(), "SNIPPET\n");
        assert_eq!(
            fs::read_to_string(&out.config_path).unwrap(),
            "Include stitch.conf\n"
        );
        assert_eq!(mode(&out.conf_path), 0o600);
        assert_eq!(mode(&out.config_path), 0o600);

        // Idempotent.
        let again = install(home.path(), "SNIPPET\n").unwrap();
        assert!(!again.conf_written);
        assert_eq!(again.include, IncludeStatus::AlreadyPresent);
        assert_eq!(
            fs::read_to_string(&out.config_path).unwrap(),
            "Include stitch.conf\n"
        );

        // A changed snippet is rewritten.
        let changed = install(home.path(), "NEW\n").unwrap();
        assert!(changed.conf_written);
        assert_eq!(fs::read_to_string(&out.conf_path).unwrap(), "NEW\n");
        // No temporary files left behind.
        assert_eq!(fs::read_dir(&ssh).unwrap().count(), 2);
    }

    #[test]
    fn install_preserves_existing_config() {
        let home = tempfile::tempdir().unwrap();
        let ssh = home.path().join(".ssh");
        fs::create_dir(&ssh).unwrap();
        let config = ssh.join("config");
        let original = "# my config\nHost foo\n    User bar\n";
        fs::write(&config, original).unwrap();
        fs::set_permissions(&config, fs::Permissions::from_mode(0o644)).unwrap();
        let out = install(home.path(), "S\n").unwrap();
        assert_eq!(out.include, IncludeStatus::Added);
        assert_eq!(
            fs::read_to_string(&config).unwrap(),
            format!("Include stitch.conf\n{original}")
        );
        assert_eq!(mode(&config), 0o644);
        assert_eq!(
            install(home.path(), "S\n").unwrap().include,
            IncludeStatus::AlreadyPresent
        );
        assert_eq!(
            fs::read_to_string(&config).unwrap(),
            format!("Include stitch.conf\n{original}")
        );
    }

    #[test]
    fn recognises_existing_includes() {
        let home = Path::new("/home/me");
        for (config, expected) in [
            ("Include stitch.conf\n", Some(true)),
            ("  include   stitch.conf\n", Some(true)),
            ("INCLUDE=stitch.conf\n", Some(true)),
            ("Include \"stitch.conf\"\n", Some(true)),
            ("Include other.conf ~/.ssh/stitch.conf\n", Some(true)),
            ("Include /home/me/.ssh/stitch.conf\n", Some(true)),
            ("User x\nInclude stitch.conf\nHost a\n", Some(true)),
            ("Host a\n  Include stitch.conf\n", Some(false)),
            ("Match all\nInclude stitch.conf\n", Some(false)),
            ("# Include stitch.conf\n", None),
            ("Include stitch.conf.bak\n", None),
            ("Include other.conf\n", None),
            ("", None),
        ] {
            assert_eq!(find_include(config, home), expected, "{config:?}");
        }
    }

    #[test]
    fn include_in_block_is_left_alone() {
        let home = tempfile::tempdir().unwrap();
        let ssh = home.path().join(".ssh");
        fs::create_dir(&ssh).unwrap();
        let original = "Host *\n    Include stitch.conf\n";
        fs::write(ssh.join("config"), original).unwrap();
        let out = install(home.path(), "S\n").unwrap();
        assert_eq!(out.include, IncludeStatus::PresentInBlock);
        assert_eq!(fs::read_to_string(ssh.join("config")).unwrap(), original);
    }

    #[test]
    fn install_through_symlink() {
        let home = tempfile::tempdir().unwrap();
        let ssh = home.path().join(".ssh");
        fs::create_dir(&ssh).unwrap();
        let dotfiles = home.path().join("dotfiles");
        fs::create_dir(&dotfiles).unwrap();
        let real = dotfiles.join("ssh_config");
        fs::write(&real, "Host x\n").unwrap();
        symlink(&real, ssh.join("config")).unwrap();
        install(home.path(), "S\n").unwrap();
        assert!(
            fs::symlink_metadata(ssh.join("config"))
                .unwrap()
                .file_type()
                .is_symlink()
        );
        assert_eq!(
            fs::read_to_string(&real).unwrap(),
            "Include stitch.conf\nHost x\n"
        );
    }
}
